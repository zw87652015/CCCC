import AppKit

enum ClipReader {
    static let concealed = "org.nspasteboard.ConcealedType"
    static let transient = "org.nspasteboard.TransientType"
    static let autoGenerated = "org.nspasteboard.AutoGeneratedType"
    static let fileURL = NSPasteboard.PasteboardType.fileURL.rawValue
    static let text = NSPasteboard.PasteboardType.string.rawValue
    static let png = NSPasteboard.PasteboardType.png.rawValue
    static let tiff = NSPasteboard.PasteboardType.tiff.rawValue

    static func read(app: String?) -> Content? {
        let pb = NSPasteboard.general
        let types = (pb.types ?? []).map { $0.rawValue }
        guard !types.isEmpty else { return nil }

        let c = Content()
        if types.contains(concealed) || types.contains(transient) { return priv(c) }
        if types.contains(autoGenerated) {
            c.quiet = true
            c.sig = "auto:" + types.joined(separator: "|")
            return c
        }
        if #available(macOS 15.4, *), !canReadContents(pb) {
            return restricted(c, types, app)
        }

        if types.contains(fileURL),
           let urls = pb.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL],
           !urls.isEmpty {
            files(c, urls.map { $0.path })
            return c
        }

        if let s = pb.string(forType: .string), !s.isEmpty {
            fillText(c, s)
            return c
        }

        if types.contains(png) || types.contains(tiff), let img = NSImage(pasteboard: pb), let c2 = image(c, img) {
            return c2
        }

        return other(c, types, app)
    }

    @available(macOS 15.4, *)
    private static func canReadContents(_ pb: NSPasteboard) -> Bool {
        switch pb.accessBehavior {
        case .default, .alwaysAllow: return true
        default: return false
        }
    }

    private static func priv(_ c: Content) -> Content {
        c.meta = L.private_
        c.sub = L.privateSub
        c.hold = L.privateSub
        return c
    }

    // Pasteboard access is restricted: name the type from the type list only, never touch the contents.
    private static func restricted(_ c: Content, _ types: [String], _ app: String?) -> Content {
        if types.contains(text) {
            c.meta = L.text
        } else if types.contains(fileURL) {
            c.meta = L.file
        } else if types.contains(png) || types.contains(tiff) {
            c.meta = L.image
        } else {
            return other(c, types, app)
        }
        c.sub = L.previewNeedsPaste
        c.sig = "types:" + types.joined(separator: "|")
        return c
    }

    private static func other(_ c: Content, _ types: [String], _ app: String?) -> Content {
        let isPublic = types.contains { $0.hasPrefix("public.") || $0.hasPrefix("com.apple.") || $0.hasPrefix("NS") }
        if isPublic {
            c.sub = L.rich
            c.hold = L.rich
            c.sig = "fmt:" + types.joined(separator: "|")
            return c
        }
        c.meta = L.appData
        c.sub = app.map(L.keptIn) ?? L.rich
        c.hold = app.map(L.appContent) ?? L.rich
        c.sig = "app:" + (app ?? "") + ":" + types.joined(separator: "|")
        return c
    }

    private static func files(_ c: Content, _ paths: [String]) {
        if paths.count == 1 {
            var isDir: ObjCBool = false
            FileManager.default.fileExists(atPath: paths[0], isDirectory: &isDir)
            c.meta = isDir.boolValue ? L.folder : L.file
            c.sub = name(paths[0])
        } else {
            c.meta = L.items(paths.count)
            c.sub = paths.prefix(8).map { name($0) }.joined(separator: ", ")
        }
        c.hold = c.sub
        c.sig = "files:\(paths.count):" + paths.joined(separator: "|").hashValue.description
    }

    private static func name(_ path: String) -> String {
        let n = (path as NSString).lastPathComponent
        return n.isEmpty ? path : n
    }

    private static func fillText(_ c: Content, _ t: String) {
        let trimmed = t.trimmingCharacters(in: .whitespacesAndNewlines)
        let lines = 1 + trimmed.filter { $0 == "\n" }.count
        if lines == 1, !trimmed.contains(" "), let u = URL(string: trimmed), let scheme = u.scheme?.lowercased(),
           scheme == "http" || scheme == "https" {
            c.meta = L.link
            c.sub = flatten(String(trimmed.dropFirst(scheme.count + 3)))
        } else {
            c.meta = lines > 1 ? L.lines(lines) : L.chars(t.utf16.count)
            c.sub = trimmed.isEmpty ? L.blank : flatten(trimmed)
        }
        c.hold = c.sub
        c.sig = "txt:\(t.utf16.count):\(t.hashValue)"
    }

    private static func flatten(_ s: String) -> String {
        var out = ""
        var space = false
        for ch in s {
            if ch.isWhitespace { space = !out.isEmpty; continue }
            if space { out.append(" "); space = false }
            out.append(ch)
            if out.count >= 200 { break }
        }
        return out
    }

    private static func image(_ c: Content, _ img: NSImage) -> Content? {
        let best = img.representations.compactMap { $0 as? NSBitmapImageRep }
            .max { $0.pixelsWide * $0.pixelsHigh < $1.pixelsWide * $1.pixelsHigh }
        guard let src = best?.cgImage ?? img.cgImage(forProposedRect: nil, context: nil, hints: nil) else { return nil }
        let sub = "\(src.width) × \(src.height)"
        c.meta = L.image
        c.sub = sub
        c.hold = L.imageHold + sub
        let thumb = thumbnail(src, 80)
        c.thumb = thumb
        c.sig = "img:" + sub + ":" + Raster.fnv(thumb)
        return c
    }

    private static func thumbnail(_ src: CGImage, _ size: Int) -> CGImage {
        let ctx = Raster.context(size, size)
        ctx.interpolationQuality = .high
        let s = CGFloat(size), w = CGFloat(src.width), h = CGFloat(src.height)
        let k = max(s / w, s / h)
        let dw = w * k, dh = h * k
        ctx.draw(src, in: CGRect(x: (s - dw) / 2, y: (s - dh) / 2, width: dw, height: dh))
        return ctx.makeImage()!
    }
}
